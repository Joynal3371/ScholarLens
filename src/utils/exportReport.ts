/**
 * Converts an SVG element in the DOM into a high-DPI PNG data URL.
 */
export async function svgElementToPngDataUrl(
  svgEl: SVGSVGElement,
  title: string,
  subtitle: string,
  darkTheme: boolean = false
): Promise<string> {
  const bbox = svgEl.viewBox?.baseVal;
  const svgW = bbox && bbox.width > 0 ? bbox.width : svgEl.clientWidth || 560;
  const svgH = bbox && bbox.height > 0 ? bbox.height : svgEl.clientHeight || 320;

  const pad = 28;
  const headerH = 54;
  const totalW = svgW + pad * 2;
  const totalH = svgH + headerH + pad * 2;
  const scale = 2;

  const serializer = new XMLSerializer();
  const clone = svgEl.cloneNode(true) as SVGSVGElement;
  clone.setAttribute('xmlns', 'http://www.w3.org/2000/svg');
  clone.setAttribute('width', String(svgW));
  clone.setAttribute('height', String(svgH));

  const svgStr = serializer.serializeToString(clone);
  const svgBlob = new Blob([svgStr], {
    type: 'image/svg+xml;charset=utf-8',
  });
  const url = URL.createObjectURL(svgBlob);

  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = totalW * scale;
      canvas.height = totalH * scale;
      const ctx = canvas.getContext('2d');
      if (!ctx) {
        URL.revokeObjectURL(url);
        reject(new Error('Canvas context unavailable'));
        return;
      }

      ctx.scale(scale, scale);

      // Background
      ctx.fillStyle = darkTheme ? '#0f172a' : '#ffffff';
      ctx.fillRect(0, 0, totalW, totalH);

      // Border
      ctx.strokeStyle = darkTheme ? '#1e293b' : '#e2e8f0';
      ctx.lineWidth = 1;
      ctx.strokeRect(0.5, 0.5, totalW - 1, totalH - 1);

      // Title
      ctx.fillStyle = darkTheme ? '#f8fafc' : '#0f172a';
      ctx.font = 'bold 16px -apple-system, BlinkMacSystemFont, sans-serif';
      ctx.fillText(title, pad, pad + 16);

      // Subtitle
      ctx.fillStyle = darkTheme ? '#94a3b8' : '#64748b';
      ctx.font = '12px -apple-system, BlinkMacSystemFont, sans-serif';
      ctx.fillText(subtitle, pad, pad + 36);

      // Draw SVG chart
      ctx.drawImage(img, pad, pad + headerH, svgW, svgH);

      URL.revokeObjectURL(url);
      resolve(canvas.toDataURL('image/png'));
    };
    img.onerror = (err) => {
      URL.revokeObjectURL(url);
      reject(err);
    };
    img.src = url;
  });
}

/**
 * Triggers a browser download of a specific chart SVG as a crisp PNG image.
 */
export async function exportChartSvgAsPng(
  chartId: string,
  title: string,
  subtitle: string,
  filename: string,
  darkTheme: boolean = false
): Promise<boolean> {
  const container = document.getElementById(chartId);
  const svgEl = container?.querySelector('svg') as SVGSVGElement | null;
  if (!svgEl) return false;

  const dataUrl = await svgElementToPngDataUrl(
    svgEl,
    title,
    subtitle,
    darkTheme
  );
  const link = document.createElement('a');
  link.href = dataUrl;
  link.download = filename.endsWith('.png') ? filename : `${filename}.png`;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  return true;
}

/**
 * Generates and downloads a comprehensive multi-page PDF report for the researcher profile.
 */
export async function generateResearcherPdfReport(params: {
  profile: ResearcherProfile;
  stats: ProfileStatistics;
  universities: UniversityCollaboration[];
  coAuthors: CoAuthorSummary[];
  countries: CountryCollaboration[];
  journals: JournalSummary[];
}): Promise<void> {
  const { profile, stats, universities, coAuthors, countries, journals } =
    params;

  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageW = 210;
  const margin = 14;
  let y = 16;

  // Header Banner
  doc.setFillColor(15, 23, 42);
  doc.rect(0, 0, pageW, 36, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(18);
  doc.text(profile.name, margin, 15);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(203, 213, 225);
  doc.text(
    `${profile.affiliation} · Scholar ID: ${profile.scholarUserId}`,
    margin,
    22
  );
  doc.text(
    `Fields: ${profile.fields.join(', ')} · Generated by ScholarLens`,
    margin,
    28
  );

  y = 45;

  // Section 1: Core Overview Statistics
  doc.setTextColor(15, 23, 42);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text('1. Core Profile Overview', margin, y);
  y += 6;

  const kpiItems = [
    ['Total Publications', String(stats.totalPapers)],
    ['Total Citations', stats.totalCitations.toLocaleString()],
    ['h-index / i10-index', `${stats.hIndex} / ${stats.i10Index}`],
    ['g-index', String(stats.gIndex)],
    [
      'Q1 Share (Total / Journals)',
      `${stats.quartileBreakdown.Q1.percentageOfTotal}% / ${stats.quartileBreakdown.Q1.percentageOfRankedJournals}%`,
    ],
    ['Q1 + Q2 Combined Share', `${stats.q1Q2CombinedPercentage}%`],
    ['Mean Citations / Paper', String(stats.meanCitationsPerPaper)],
    ['Annual Citation Velocity', `${stats.annualCitationVelocity}/yr`],
    ['Collaborating Universities', String(universities.length)],
    ['Collaborating Countries', String(countries.length)],
    ['Total Co-Authors', String(coAuthors.length)],
    ['Open Access Ratio', `${stats.openAccessPercentage}%`],
  ];

  const colW = (pageW - margin * 2) / 3;
  const boxH = 14;
  kpiItems.forEach((item, idx) => {
    const col = idx % 3;
    const row = Math.floor(idx / 3);
    const bx = margin + col * colW;
    const by = y + row * (boxH + 2);

    doc.setFillColor(248, 250, 252);
    doc.setDrawColor(226, 232, 240);
    doc.roundedRect(bx, by, colW - 2, boxH, 1.5, 1.5, 'FD');

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(100, 116, 139);
    doc.text(item[0], bx + 3, by + 5);

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(15, 23, 42);
    doc.text(item[1], bx + 3, by + 11.5);
  });

  y += Math.ceil(kpiItems.length / 3) * (boxH + 2) + 8;

  // Section 2: Quartile (Q1-Q4), Conference & Non-Indexed Breakdown (100% Total)
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(15, 23, 42);
  doc.text('2. Portfolio Indexing & Quartile Breakdown (100% Total)', margin, y);
  y += 6;

  doc.setFontSize(9);
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageW - margin * 2, 7, 'F');
  doc.text('Portfolio Category', margin + 2, y + 5);
  doc.text('Papers', margin + 90, y + 5);
  doc.text('% of Total Portfolio', margin + 120, y + 5);
  doc.text('Citations', margin + 158, y + 5);
  y += 7;

  const pKeys: {
    key: 'Q1' | 'Q2' | 'Q3' | 'Q4' | 'Conference' | 'Non-Indexed';
    label: string;
  }[] = [
    { key: 'Q1', label: 'Q1 Indexed Journals' },
    { key: 'Q2', label: 'Q2 Indexed Journals' },
    { key: 'Q3', label: 'Q3 Indexed Journals' },
    { key: 'Q4', label: 'Q4 Indexed Journals' },
    { key: 'Conference', label: 'Conference Papers' },
    { key: 'Non-Indexed', label: 'Non-Indexed Papers' },
  ];
  doc.setFont('helvetica', 'normal');
  pKeys.forEach(({ key, label }) => {
    const d = stats.portfolioDistribution[key];
    doc.setDrawColor(241, 245, 249);
    doc.line(margin, y + 6, pageW - margin, y + 6);
    doc.text(label, margin + 2, y + 4.5);
    doc.text(String(d.count), margin + 90, y + 4.5);
    doc.text(`${d.percentage}%`, margin + 120, y + 4.5);
    doc.text(d.citations.toLocaleString(), margin + 158, y + 4.5);
    y += 6.5;
  });

  // Total 100% Row
  doc.setFont('helvetica', 'bold');
  doc.text('Total Portfolio', margin + 2, y + 4.5);
  doc.text(String(stats.totalPapers), margin + 90, y + 4.5);
  doc.text('100.0%', margin + 120, y + 4.5);
  doc.text(stats.totalCitations.toLocaleString(), margin + 158, y + 4.5);
  y += 8;

  // Try embedding live chart snapshots if present in DOM
  try {
    const donutContainer = document.getElementById('chart-quartile-donut');
    const trendContainer = document.getElementById('chart-yearly-trend');
    const donutSvg = donutContainer?.querySelector('svg') as SVGSVGElement | null;
    const trendSvg = trendContainer?.querySelector('svg') as SVGSVGElement | null;

    if (donutSvg && trendSvg && y < 215) {
      y += 6;
      const donutUrl = await svgElementToPngDataUrl(
        donutSvg,
        'Quartile Distribution',
        `${profile.name}`,
        false
      );
      const trendUrl = await svgElementToPngDataUrl(
        trendSvg,
        'Yearly Output & Citations',
        `${profile.name}`,
        false
      );
      doc.addImage(donutUrl, 'PNG', margin, y, 86, 52);
      doc.addImage(trendUrl, 'PNG', margin + 92, y, 88, 52);
    }
  } catch {
    // Continue if SVG serialization is skipped
  }

  // Page 2: Collaborating Universities, Countries, Co-Authors & Venues
  doc.addPage();
  y = 18;

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.setTextColor(15, 23, 42);
  doc.text(
    `3. Collaborating Universities (${universities.length}) & Countries (${countries.length})`,
    margin,
    y
  );
  y += 6;

  doc.setFontSize(8.5);
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageW - margin * 2, 6.5, 'F');
  doc.text('University', margin + 2, y + 4.5);
  doc.text('Country', margin + 88, y + 4.5);
  doc.text('Co-Authors', margin + 125, y + 4.5);
  doc.text('Papers', margin + 148, y + 4.5);
  doc.text('Citations', margin + 165, y + 4.5);
  y += 6.5;

  doc.setFont('helvetica', 'normal');
  universities.slice(0, 14).forEach((u) => {
    doc.text(u.universityName.slice(0, 46), margin + 2, y + 4.5);
    doc.text(u.country.slice(0, 20), margin + 88, y + 4.5);
    doc.text(String(u.coAuthors.length), margin + 128, y + 4.5);
    doc.text(String(u.paperCount), margin + 150, y + 4.5);
    doc.text(u.totalCitations.toLocaleString(), margin + 165, y + 4.5);
    y += 6;
  });

  y += 6;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(`4. Top Co-Authors (${coAuthors.length})`, margin, y);
  y += 6;

  doc.setFontSize(8.5);
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageW - margin * 2, 6.5, 'F');
  doc.text('Co-Author Name', margin + 2, y + 4.5);
  doc.text('Affiliation', margin + 58, y + 4.5);
  doc.text('Country', margin + 125, y + 4.5);
  doc.text('Papers', margin + 150, y + 4.5);
  doc.text('Citations', margin + 165, y + 4.5);
  y += 6.5;

  doc.setFont('helvetica', 'normal');
  coAuthors.slice(0, 14).forEach((ca) => {
    doc.text(ca.name.slice(0, 30), margin + 2, y + 4.5);
    doc.text(ca.universityName.slice(0, 36), margin + 58, y + 4.5);
    doc.text(ca.country.slice(0, 16), margin + 125, y + 4.5);
    doc.text(String(ca.paperCount), margin + 152, y + 4.5);
    doc.text(ca.totalCitations.toLocaleString(), margin + 165, y + 4.5);
    y += 6;
  });

  y += 6;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(`5. Top Journals & Conference Venues (${journals.length})`, margin, y);
  y += 6;

  doc.setFontSize(8.5);
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageW - margin * 2, 6.5, 'F');
  doc.text('Venue Name', margin + 2, y + 4.5);
  doc.text('Type', margin + 108, y + 4.5);
  doc.text('Quartile', margin + 132, y + 4.5);
  doc.text('Papers', margin + 152, y + 4.5);
  doc.text('Citations', margin + 165, y + 4.5);
  y += 6.5;

  doc.setFont('helvetica', 'normal');
  journals.slice(0, 10).forEach((j) => {
    doc.text(j.venue.slice(0, 56), margin + 2, y + 4.5);
    doc.text(j.type, margin + 108, y + 4.5);
    doc.text(j.quartile, margin + 132, y + 4.5);
    doc.text(String(j.paperCount), margin + 154, y + 4.5);
    doc.text(j.totalCitations.toLocaleString(), margin + 165, y + 4.5);
    y += 6;
  });

  // Page 3: Publications Inventory
  doc.addPage();
  y = 18;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(13);
  doc.text(
    `6. Complete Publications List (${profile.publications.length})`,
    margin,
    y
  );
  y += 6;

  doc.setFontSize(8);
  doc.setFillColor(241, 245, 249);
  doc.rect(margin, y, pageW - margin * 2, 6.5, 'F');
  doc.text('Title', margin + 2, y + 4.5);
  doc.text('Venue', margin + 98, y + 4.5);
  doc.text('Quartile', margin + 142, y + 4.5);
  doc.text('Year', margin + 156, y + 4.5);
  doc.text('Citations', margin + 167, y + 4.5);
  y += 6.5;

  doc.setFont('helvetica', 'normal');
  profile.publications.slice(0, 34).forEach((p) => {
    if (y > 276) {
      doc.addPage();
      y = 18;
    }
    doc.text(p.title.slice(0, 52), margin + 2, y + 4.5);
    doc.text(p.venue.slice(0, 24), margin + 98, y + 4.5);
    doc.text(p.quartile, margin + 142, y + 4.5);
    doc.text(String(p.year), margin + 156, y + 4.5);
    doc.text(p.citations.toLocaleString(), margin + 167, y + 4.5);
    y += 6;
  });

  doc.save(`${profile.scholarUserId}_scholar_profile_report.pdf`);
}
