export function findVerifiedPresetProfile(
  userId: string,
  queryName?: string
): ResearcherProfile | null {
  const lowerId = userId.toLowerCase();
  for (const preset of PRESET_PROFILES) {
    if (
      preset.scholarUserId.toLowerCase() === lowerId ||
      preset.id.toLowerCase() === lowerId ||
      (queryName &&
        preset.name.toLowerCase().includes(queryName.toLowerCase()))
    ) {
      return preset;
    }
  }
  return null;
}
